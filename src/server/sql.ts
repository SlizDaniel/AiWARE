/** Bump when SCHEMA_SQL changes so existing databases run the DDL again. */
export const SCHEMA_VERSION = 3

async function schemaIsCurrent(db: Db): Promise<boolean> {
  // to_regclass never raises, so this is safe inside a caller's transaction.
  const [table] = await db.query<{ found: boolean }>("SELECT to_regclass('app_meta') IS NOT NULL AS found")
  if (!table?.found) return false
  const rows = await db.query<{ value: number }>("SELECT value FROM app_meta WHERE key = 'schema_version'")
  return rows[0]?.value === SCHEMA_VERSION
}

/**
 * Creates tables/indexes if missing. A cold start on an up-to-date database
 * costs one SELECT; otherwise the DDL runs once, serialised by an advisory
 * lock so concurrent cold starts don't race.
 */
export async function ensureSchema(db: Db): Promise<void> {
  if (await schemaIsCurrent(db)) return
  await db.transaction(async (tx) => {
    await tx.query('SELECT pg_advisory_xact_lock(724242)')
    await tx.exec(SCHEMA_SQL)
    await tx.query(
      `INSERT INTO app_meta (key, value) VALUES ('schema_version', $1)
       ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`,
      [SCHEMA_VERSION],
    )
  })
}

// ---------------------------------------------------------------- time helpers

/**
 * SQL expression formatting a timestamptz column as local 'YYYY-MM-DD HH:MM:SS'
 * text, e.g. `SELECT ${tsText('ts')} FROM audit_log` → column "ts".
 */
export function tsText(column: string, alias = column.split('.').pop() ?? column): string {
  if (!/^[a-z_][a-z0-9_.]*$/.test(column) || !/^[a-z_][a-z0-9_]*$/.test(alias)) {
    throw new Error(`Invalid column name: ${column}`)
  }
  return `to_char(${column} AT TIME ZONE '${appTimezone()}', 'YYYY-MM-DD HH24:MI:SS') AS ${alias}`
}

/** SQL expression formatting a DATE column as 'YYYY-MM-DD' text. */
export function dateText(column: string, alias = column.split('.').pop() ?? column): string {
  if (!/^[a-z_][a-z0-9_.]*$/.test(column) || !/^[a-z_][a-z0-9_]*$/.test(alias)) {
    throw new Error(`Invalid column name: ${column}`)
  }
  return `to_char(${column}, 'YYYY-MM-DD') AS ${alias}`
}

/** Today's date in APP_TIMEZONE as 'YYYY-MM-DD'. */
export function todayLocal(now: Date = new Date()): string {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: appTimezone(),
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(now)
  const get = (type: string) => parts.find((part) => part.type === type)?.value ?? ''
  return `${get('year')}-${get('month')}-${get('day')}`
}

/** Next Tuesday strictly after `today` ('YYYY-MM-DD'), like the Python _next_tuesday. */
export function nextTuesday(today: string = todayLocal()): string {
  const [year, month, day] = today.split('-').map(Number)
  const date = new Date(Date.UTC(year, month - 1, day))
  const weekday = (date.getUTCDay() + 6) % 7 // Monday = 0, like Python's weekday()
  const daysUntil = (1 - weekday + 7) % 7 || 7
  date.setUTCDate(date.getUTCDate() + daysUntil)
  return date.toISOString().slice(0, 10)
}
