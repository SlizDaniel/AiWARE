// Database access layer: one tiny `Db` interface over two Postgres engines.
//   - postgres.js → Supabase Postgres (production, via the connection pooler)
//   - PGlite      → in-process Postgres (local dev without Supabase, tests)
// Domain code writes plain Postgres SQL with $1, $2… placeholders.
import postgres from 'postgres'
import type { PGlite, Transaction as PgliteTransaction } from '@electric-sql/pglite'
import { appTimezone } from './env'

export type Row = Record<string, unknown>

export interface Db {
  /**
   * Parametrised query ($1, $2…). Returns plain row objects.
   * JSONB parameters: pass JSON.stringify(value) and cast `$n::text::jsonb` —
   * a bare `$n::jsonb` makes postgres.js stringify the string a second time.
   */
  query<T extends Row = Row>(text: string, params?: unknown[]): Promise<T[]>
  /** Runs several statements without parameters (DDL). */
  exec(text: string): Promise<void>
  /**
   * Runs `fn` inside one transaction (commit on success, rollback on throw).
   * Inside `fn` use ONLY the `tx` argument — PGlite has a single connection,
   * so a query on the outer Db would wait for the transaction forever.
   * Calling transaction() on a tx just runs `fn` in the same transaction.
   */
  transaction<T>(fn: (tx: Db) => Promise<T>): Promise<T>
}

// ---------------------------------------------------------------- postgres.js

function sanitisePostgresUrl(raw: string): string {
  // Vercel/Supabase URLs carry params such as ?sslmode=require&supa=base-pooler.x;
  // postgres.js would forward unknown ones as startup parameters. SSL is set below.
  const url = new URL(raw)
  url.search = ''
  return url.toString()
}

function isLocalHost(raw: string): boolean {
  const host = new URL(raw).hostname
  return host === 'localhost' || host === '127.0.0.1' || host === '::1'
}

type PgClient = postgres.Sql | postgres.TransactionSql

function wrapPostgres(sql: PgClient, inTransaction: boolean): Db {
  const db: Db = {
    async query<T extends Row = Row>(text: string, params: unknown[] = []) {
      const rows = await sql.unsafe(text, params as postgres.ParameterOrJSON<never>[])
      return Array.from(rows) as unknown as T[]
    },
    async exec(text: string) {
      await sql.unsafe(text)
    },
    async transaction<T>(fn: (tx: Db) => Promise<T>): Promise<T> {
      if (inTransaction) return fn(db)
      const result = await (sql as postgres.Sql).begin((tx) => fn(wrapPostgres(tx, true)))
      return result as T
    },
  }
  return db
}

export function createPostgresDb(url: string): Db {
  const sql = postgres(sanitisePostgresUrl(url), {
    // Supabase's transaction pooler (port 6543) does not support prepared statements.
    prepare: false,
    max: 5,
    idle_timeout: 20,
    connect_timeout: 10,
    ssl: isLocalHost(url) ? false : 'require',
    onnotice: () => {},
  })
  return wrapPostgres(sql, false)
}

// --------------------------------------------------------------------- PGlite

type PgliteClient = PGlite | PgliteTransaction

function wrapPglite(pg: PgliteClient, inTransaction: boolean): Db {
  const db: Db = {
    async query<T extends Row = Row>(text: string, params: unknown[] = []) {
      const result = await pg.query<T>(text, params)
      return result.rows
    },
    async exec(text: string) {
      await pg.exec(text)
    },
    async transaction<T>(fn: (tx: Db) => Promise<T>): Promise<T> {
      if (inTransaction) return fn(db)
      return (pg as PGlite).transaction((tx) => fn(wrapPglite(tx, true)))
    },
  }
  return db
}

/** dataDir null → in-memory database (tests, ephemeral serverless fallback). */
export async function createPgliteDb(dataDir: string | null): Promise<Db> {
  const { PGlite } = await import('@electric-sql/pglite')
  if (dataDir) {
    const { mkdirSync } = await import('node:fs')
    mkdirSync(dataDir, { recursive: true })
  }
  const pg = dataDir ? new PGlite(dataDir) : new PGlite()
  await pg.waitReady
  return wrapPglite(pg, false)
}

